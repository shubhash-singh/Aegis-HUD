/**
 * Precomputed 2D layout of the brain surface (lateral view), generated offline.
 *
 * Every part is a triangulated patch:
 * - nodes: `u v t b` per node. u = front(-1) to back(+1), v = top(-) to bottom(+), both in
 *   units of half the brain length. t = 0 on the outline up to 1 deep inside (drives thickness).
 *   b = 1 for outline nodes (they sit on the mid-plane and are shared by both sides).
 * - tris: node-index triples (used for surface normals).
 * - edges: `a b rim` triples (the lines that get drawn; rim = 1 for outline segments).
 *
 * Regenerating this file changes the brain's look; the 3D shell is built in [NeuralMesh3D].
 */
internal class BrainPart(
    val h: Float,
    val u: FloatArray,
    val v: FloatArray,
    val t: FloatArray,
    val boundary: BooleanArray,
    val tris: IntArray,
    val edges: IntArray,
) {
    val nodeCount: Int get() = u.size
}

