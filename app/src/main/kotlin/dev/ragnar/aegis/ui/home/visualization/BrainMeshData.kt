    private fun parsePart(h: Float, nodes: String, tris: String, edges: String): BrainPart {
        val nt = nodes.split(' ')
        val n = nt.size / 4
        val u = FloatArray(n)
        val v = FloatArray(n)
        val t = FloatArray(n)
        val b = BooleanArray(n)
        for (i in 0 until n) {
            u[i] = nt[i * 4].toFloat()
            v[i] = nt[i * 4 + 1].toFloat()
            t[i] = nt[i * 4 + 2].toFloat()
            b[i] = nt[i * 4 + 3] == "1"
        }
        return BrainPart(
            h, u, v, t, b,
            tris.split(' ').map { it.toInt() }.toIntArray(),
            edges.split(' ').map { it.toInt() }.toIntArray(),
        )
    }

